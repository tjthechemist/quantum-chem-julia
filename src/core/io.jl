# ==============================================================================
# QuantumChemMM.jl: Chemical File Formats IO (XYZ, PDB, MOL)
# ==============================================================================

module ChemIO

using ..Types
using ..Elements
using ..Topology
using Printf

export read_xyz, write_xyz, parse_xyz, read_pdb, write_pdb

"""
    parse_xyz(xyz_str::String; name::String="Molecule")::Molecule
Parses an XYZ format string directly into a Molecule struct.
"""
function parse_xyz(xyz_str::String; name::String="Molecule")::Molecule
    lines = filter(!isempty, strip.(split(xyz_str, '\n')))
    if length(lines) < 3
        throw(ArgumentError("Invalid XYZ format: must have at least 3 lines."))
    end
    natoms = parse(Int, lines[1])
    comment = lines[2]
    mol = Molecule(name)

    for i in 1:natoms
        tokens = split(lines[2 + i])
        sym = Symbol(tokens[1])
        x = parse(Float64, tokens[2])
        y = parse(Float64, tokens[3])
        z = parse(Float64, tokens[4])
        push!(mol.atoms, Atom(i, sym, [x, y, z]))
    end

    perceive_topology!(mol)
    return mol
end

"""
    read_xyz(filename::String)::Molecule
Reads an XYZ file from disk.
"""
function read_xyz(filename::String)::Molecule
    content = read(filename, String)
    basename_noext = splitext(basename(filename))[1]
    return parse_xyz(content; name=basename_noext)
end

"""
    write_xyz(filename::String, mol::Molecule; comment::String="")
Writes a Molecule to an XYZ file.
"""
function write_xyz(filename::String, mol::Molecule; comment::String="")
    open(filename, "w") do io
        println(io, n_atoms(mol))
        println(io, isempty(comment) ? "Generated by QuantumChemMM.jl ($(mol.name))" : comment)
        for at in mol.atoms
            @printf(io, "%-3s %12.6f %12.6f %12.6f\n", string(at.symbol), at.coords[1], at.coords[2], at.coords[3])
        end
    end
end

"""
    read_pdb(filename::String)::Molecule
Reads atomic coordinates and elements from a PDB file.
"""
function read_pdb(filename::String)::Molecule
    lines = readlines(filename)
    mol = Molecule(splitext(basename(filename))[1])
    idx = 1
    for line in lines
        if startswith(line, "ATOM") || startswith(line, "HETATM")
            if length(line) >= 54
                sym_str = strip(line[77:min(78, length(line))])
                if isempty(sym_str)
                    sym_str = strip(line[13:14])
                    sym_str = replace(sym_str, r"[0-9]" => "")
                end
                sym = Symbol(uppercase(sym_str))
                x = parse(Float64, strip(line[31:38]))
                y = parse(Float64, strip(line[39:46]))
                z = parse(Float64, strip(line[47:54]))
                push!(mol.atoms, Atom(idx, sym, [x, y, z]))
                idx += 1
            end
        end
    end
    perceive_topology!(mol)
    return mol
end

"""
    write_pdb(filename::String, mol::Molecule)
Writes molecule to a basic PDB format file.
"""
function write_pdb(filename::String, mol::Molecule)
    open(filename, "w") do io
        println(io, "REMARK   Generated by QuantumChemMM.jl")
        for at in mol.atoms
            @printf(io, "HETATM%5d %-4s MOL     1    %8.3f%8.3f%8.3f  1.00  0.00          %2s\n",
                    at.index, string(at.symbol), at.coords[1], at.coords[2], at.coords[3], string(at.symbol))
        end
        for b in mol.bonds
            @printf(io, "CONECT%5d%5d\n", b.i, b.j)
        end
        println(io, "END")
    end
end

end # module ChemIO

